/**
 * Generates the core's widgets into packages/codegen/out: in-place JavaScript (formatted by oxfmt) with its
 * declarations, and LuaJIT, or the reason a widget's Lua is refused. With `--check`, only checks the widgets against
 * the source subset. Either way, a rule broken is printed and fails it.
 */

import { check, generate } from '../packages/codegen/src/index.js'

const ROOT = new URL('..', import.meta.url).pathname
const OUT = `${ROOT}packages/codegen/out`
const options = {
  header: '// Generated by @pterror/interact-codegen from @pterror/interact-core. Do not edit.',
  index: `${ROOT}packages/core/src/index.js`,
  root: ROOT,
  source: (/** @type {string} */ module) =>
    `@pterror/interact-core/${module.replace(/^.*\/(?<name>[\w-]+)\.js$/u, '$<name>')}`,
  tsconfig: `${ROOT}packages/core/tsconfig.json`,
}

const { diagnostics, widgets } = process.argv.includes('--check')
  ? { diagnostics: check(options), widgets: [] }
  : generate(options)
for (const diagnostic of diagnostics) {
  console.error(diagnostic)
}
process.exitCode = diagnostics.length > 0 ? 1 : 0
if (widgets.length > 0) {
  const made = await Bun.$`mktemp -d -t interact-codegen-XXXXXX`.text()
  const staging = made.trim()
  /** @type {Promise<number>[]} */
  const writes = []
  for (const widget of widgets) {
    writes.push(
      Bun.write(`${staging}/${widget.name}.js`, widget.js),
      Bun.write(`${staging}/${widget.name}.d.ts`, widget.dts),
    )
    if (widget.lua === null) {
      console.warn(`${widget.name}: no Lua: ${widget.refused.join('; ')}`)
    } else {
      writes.push(Bun.write(`${staging}/${widget.name}.lua`, widget.lua))
    }
  }
  await Promise.all(writes)
  await Bun.$`${ROOT}node_modules/.bin/oxfmt --config=${ROOT}.oxfmtrc.json .`.cwd(staging).quiet()
  await Bun.$`rm -rf ${OUT} && mv ${staging} ${OUT}`
}
