/**
 * Generates the core's widgets: their in-place JavaScript, with the declarations typing it, into the core's
 * src/generated (committed: what every framework's components run), and their LuaJIT into packages/codegen/out, or the
 * reason a widget's Lua is refused. Both are formatted by oxfmt. With `--check`, generates them aside and fails if a
 * rule of the source subset is broken or the core's generated modules differ from what it generates.
 */

import { generate } from '../packages/codegen/src/index.js'

const ROOT = new URL('..', import.meta.url).pathname
const GENERATED = `${ROOT}packages/core/src/generated`
const LUA = `${ROOT}packages/codegen/out`
const checking = process.argv.includes('--check')

const { diagnostics, widgets } = generate({
  header: '// Generated by @pterror/interact-codegen from @pterror/interact-core. Do not edit.',
  index: `${ROOT}packages/core/src/index.js`,
  root: ROOT,
  source: (/** @type {string} */ module) => `../${module.replace(/^.*\/(?<name>[\w-]+)\.js$/u, '$<name>')}.js`,
  tsconfig: `${ROOT}packages/core/tsconfig.json`,
})
for (const diagnostic of diagnostics) {
  console.error(diagnostic)
}
if (diagnostics.length > 0) {
  process.exit(1)
}

const made = await Bun.$`mktemp -d -t interact-codegen-XXXXXX`.text()
const staging = made.trim()
/** @type {Promise<number>[]} */
const writes = []
for (const widget of widgets) {
  writes.push(
    Bun.write(`${staging}/generated/${widget.name}.js`, widget.js),
    Bun.write(`${staging}/generated/${widget.name}.d.ts`, widget.dts),
  )
  if (widget.lua === null) {
    console.warn(`${widget.name}: no Lua: ${widget.refused.join('; ')}`)
  } else {
    writes.push(Bun.write(`${staging}/lua/${widget.name}.lua`, widget.lua))
  }
}
await Promise.all(writes)
await Bun.$`${ROOT}node_modules/.bin/oxfmt --config=${ROOT}.oxfmtrc.json .`.cwd(staging).quiet()
if (checking) {
  const compared = await Bun.$`diff -r ${staging}/generated ${GENERATED}`.nothrow().quiet()
  if (compared.exitCode !== 0) {
    console.error(`Out of date (run bun scripts/codegen.js):\n${compared.stdout.toString()}`)
    process.exitCode = 1
  }
  await Bun.$`rm -rf ${staging}`
} else {
  await Bun.$`rm -rf ${GENERATED} ${LUA} && mv ${staging}/generated ${GENERATED} && mv ${staging}/lua ${LUA} && rm -rf ${staging}`
}
